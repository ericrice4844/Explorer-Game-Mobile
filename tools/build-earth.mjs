// Generates js/data/earth.js: a coarse equirectangular land/sea mask of Earth.
// Dev-only tool. Run with: npm run build:earth
// Source data: Natural Earth via the world-atlas package (public domain).
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { feature } from 'topojson-client';
import { geoContains } from 'd3-geo';

const require = createRequire(import.meta.url);
const W = 240;
const H = 120;

const topo = JSON.parse(readFileSync(require.resolve('world-atlas/land-50m.json'), 'utf8'));
const land = feature(topo, topo.objects.land);
// Split into single polygons with bounding boxes for speed (spherical containment via d3-geo).
const parts = [];
for (const f of land.features) {
  const g = f.geometry;
  const list = g.type === 'Polygon' ? [g.coordinates] : g.coordinates;
  for (const coords of list) {
    let minY = Infinity, maxY = -Infinity;
    for (const [, y] of coords[0]) { minY = Math.min(minY, y); maxY = Math.max(maxY, y); }
    parts.push({ geo: { type: 'Polygon', coordinates: coords }, minY, maxY });
  }
}

function isLand(lon, lat) {
  for (const p of parts) {
    if (lat < p.minY - 1 || lat > p.maxY + 1) continue;
    if (geoContains(p.geo, [lon, lat])) return true;
  }
  return false;
}

const rows = [];
const S = 3; // 3x3 subsamples per tile
for (let y = 0; y < H; y++) {
  let row = '';
  for (let x = 0; x < W; x++) {
    let hits = 0;
    for (let sy = 0; sy < S; sy++) {
      for (let sx = 0; sx < S; sx++) {
        const lon = -180 + ((x + (sx + 0.5) / S) * 360) / W;
        const lat = 90 - ((y + (sy + 0.5) / S) * 180) / H;
        if (isLand(lon, lat)) hits++;
      }
    }
    // Keep small islands visible: 3 of 9 samples is enough to count as land.
    row += hits >= 3 ? '#' : '.';
  }
  rows.push(row);
}

// Run-length encode each row: "<count><char>" pairs.
const rle = rows.map((r) => r.replace(/(.)\1*/g, (m, c) => m.length + c));
const out = `// AUTO-GENERATED by tools/build-earth.mjs — do not edit by hand.
// ${W}x${H} equirectangular land mask derived from Natural Earth (public domain).
export const EARTH_W = ${W};
export const EARTH_H = ${H};
export const EARTH_RLE = [
${rle.map((r) => `  '${r}',`).join('\n')}
];
`;
writeFileSync(new URL('../js/data/earth.js', import.meta.url), out);
console.log(rows.join('\n'));
